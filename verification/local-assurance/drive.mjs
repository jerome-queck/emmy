import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { cp, mkdir, readFile, realpath, rm, symlink, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { canonical, digest } from '../../src/content.mjs';

export async function driveAssurance(sourceRoot, directory) {
  const root = join(directory, 'fixture'); await mkdir(root, { recursive: true });
  for (const path of ['src', 'scripts', 'docs', 'registry', '.agents', 'verification', 'test', 'procedures', '.github', '.codex', 'AGENTS.md', 'package-lock.json']) await cp(join(sourceRoot, path), join(root, path), { recursive: true });
  const coverage = JSON.parse(await readFile(join(sourceRoot, 'verification/publication/coverage.json'), 'utf8'));
  await writeFile(join(root, 'verification/publication/coverage.json'), JSON.stringify(coverage));
  await writeFile(join(root, '.gitignore'), '.local/\nnode_modules/\n');
  await mkdir(join(root, '.local/tools'), { recursive: true });
  await symlink(process.env.EMMY_TLC_JAR ?? join(sourceRoot, '.local/tools', coverage.tool.filename), join(root, '.local/tools', coverage.tool.filename));
  await cp(await realpath(join(sourceRoot, 'node_modules')), join(root, 'node_modules'), { recursive: true, verbatimSymlinks: true });
  await writeFile(join(root, 'package.json'), JSON.stringify({ type: 'module', scripts: { check: 'node scripts/check.mjs' } }));
  const modulePath = join(root, 'src/assurance.mjs'); const original = await readFile(modulePath, 'utf8');
  const first = original.indexOf('Object.freeze([') + 'Object.freeze(['.length;
  const last = original.indexOf('].map(row =>', first);
  assert.ok(first > 0 && last > first);
  await writeFile(modulePath, `${original.slice(0, first)}\n  { id: 'first', args: ['fixture-first.mjs'] },\n  { id: 'second', args: ['fixture-second.mjs'] },\n${original.slice(last)}`);
  const inventoryPath = join(root, 'verification/subsystems.json');
  const inventory = JSON.parse(await readFile(inventoryPath, 'utf8'));
  for (const area of inventory.subsystems) for (const file of area.files) {
    if (['src/assurance.mjs', 'package.json', '.gitignore', 'verification/publication/coverage.json'].includes(file.path)) file.sha256 = digest(await readFile(join(root, file.path)));
  }
  await writeFile(inventoryPath, JSON.stringify(inventory));
  await writeFile(join(root, 'fixture-first.mjs'), `import { readFileSync, writeFileSync } from 'node:fs';\nimport { execFileSync } from 'node:child_process';\nconst mode = readFileSync('.local/mode','utf8');\nconsole.log('original first output');\nif(mode==='fail') process.exitCode=7;\nif(mode==='drift') writeFileSync('source.txt','changed');\nif(mode==='base') execFileSync('git',['update-ref','refs/heads/acceptance-base','HEAD^']);\nif(mode==='signal') process.kill(process.pid,'SIGTERM');\n`);
  await writeFile(join(root, 'fixture-second.mjs'), "import { readFileSync, writeFileSync, existsSync } from 'node:fs'; const count=existsSync('.local/second-ran')?Number(readFileSync('.local/second-ran','utf8')):0; writeFileSync('.local/second-ran',String(count+1)); console.log('original second output');\n");
  await writeFile(join(root, 'source.txt'), 'original');
  const git = args => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git(['init', '-q']); git(['config', 'user.name', 'Synthetic assurance']); git(['config', 'user.email', 'fixture@example.invalid']); git(['add', '.']); git(['commit', '-qm', 'Synthetic assurance baseline']);
  git(['commit', '--allow-empty', '-qm', 'Synthetic second revision']); git(['branch', 'acceptance-base']);
  const commands = [];
  const run = (args, expected, executable = process.execPath, env = process.env) => {
    const result = spawnSync(executable, args, { cwd: root, env, encoding: 'utf8', timeout: 60_000, maxBuffer: 16 * 1024 * 1024 });
    commands.push({ executable, args, code: result.status, signal: result.signal, stdout: result.stdout, stderr: result.stderr });
    assert.equal(result.error, undefined); assert.equal(result.status, expected, result.stdout + result.stderr);
    return JSON.parse(result.stdout.trim().split('\n').at(-1));
  };
  const check = async (mode, expected = 0, npm = false) => {
    await writeFile(join(root, '.local/mode'), mode);
    return run(npm ? ['run', 'check', '--', '--base', 'acceptance-base'] : ['scripts/check.mjs', '--base', 'acceptance-base'], expected, npm ? 'npm' : process.execPath);
  };
  const assess = async (result, expected, env = process.env) => {
    const path = join(root, '.local/request.json');
    await writeFile(path, JSON.stringify({ receiptFile: result.receiptFile, receiptDigest: result.receiptDigest }));
    return run(['scripts/agent.mjs', 'assurance', '--file', path], expected, process.execPath, env);
  };
  const health = run(['scripts/agent.mjs', 'doctor'], 0);
  assert.equal(health.data.status, 'ready');
  const green = await check('pass', 0, true);
  assert.equal((await assess(green, 0)).data.status, 'current-local-reported');
  await writeFile(join(root, 'source.txt'), 'changed');
  assert.equal((await assess(green, 3)).data.status, 'refused');
  await writeFile(join(root, 'source.txt'), 'original');
  assert.equal((await assess(green, 0)).data.status, 'current-local-reported');
  const dependency = join(root, 'node_modules/commonmark/package.json'); const dependencyBytes = await readFile(dependency);
  await writeFile(dependency, `${dependencyBytes}\n`); await assess(green, 3); await writeFile(dependency, dependencyBytes);
  git(['commit', '--allow-empty', '-qm', 'Changed current head']); await assess(green, 3);
  const extraHead = git(['rev-parse', 'HEAD']); git(['checkout', '--detach', 'HEAD^']);
  await assess(green, 0);
  assert.ok(extraHead);
  const count = await readFile(join(root, '.local/second-ran'), 'utf8');
  const failure = await check('fail', 1);
  assert.equal(relative(root, failure.receiptFile).split(sep).slice(0, 3).join('/'), '.local/verification/local-assurance', 'Failed suite evidence stays inside existing CI upload root');
  const failed = JSON.parse(await readFile(failure.receiptFile));
  assert.equal(failed.events.filter(event => event.kind === 'finish').length, 1);
  assert.equal(failed.events.find(event => event.kind === 'finish').code, 7);
  assert.equal(await readFile(join(failure.receiptFile, '..', 'first.stdout'), 'utf8'), 'original first output\n', 'Original failed-command diagnostics remain readable under uploaded evidence');
  assert.equal(await readFile(join(root, '.local/second-ran'), 'utf8'), count, 'Failed first suite prevents second process launch');
  await assess(failure, 3);
  const signalled = await check('signal', 1); await assess(signalled, 3);
  const drift = await check('drift', 1);
  assert.equal(drift.state.reason, 'context-changed');
  await writeFile(join(root, 'source.txt'), 'original');
  const moved = await check('base', 1);
  assert.equal(moved.state.reason, 'context-changed'); git(['update-ref', 'refs/heads/acceptance-base', 'HEAD']);
  const receipt = JSON.parse(await readFile(green.receiptFile));
  const altered = async (name, edit, expected = 3) => {
    const value = structuredClone(receipt); edit(value);
    const bytes = `${canonical(value)}\n`; const path = join(root, '.local', `${name}.json`);
    await writeFile(path, bytes);
    for (const event of value.events.filter(event => event.kind === 'finish')) for (const stream of ['stdout', 'stderr']) await cp(join(green.receiptFile, '..', event[stream].file), join(root, '.local', event[stream].file));
    return assess({ receiptFile: path, receiptDigest: digest(bytes) }, expected);
  };
  await altered('missing', value => { value.events.splice(2, 2); });
  await altered('reorder', value => { [value.events[0], value.events[2]] = [value.events[2], value.events[0]]; });
  await altered('failed-result', value => { value.events[1].code = 1; });
  await altered('different-host', value => { value.initial.context.host.hostname = 'another-machine'; value.initial.contextDigest = digest(canonical(value.initial.context)); value.events.forEach(event => { event.contextDigest = value.initial.contextDigest; }); });
  await altered('different-node', value => { value.initial.context.node.version = 'other-runtime'; value.initial.contextDigest = digest(canonical(value.initial.context)); value.events.forEach(event => { event.contextDigest = value.initial.contextDigest; }); });
  await writeFile(join(green.receiptFile, '..', 'first.stdout'), 'corrupt output');
  await assess(green, 3);
  await writeFile(join(green.receiptFile, '..', 'first.stdout'), 'original first output\n');
  await assess(green, 0);
  await assess({ ...green, receiptDigest: '0'.repeat(64) }, 2);
  const restored = await check('pass'); await assess(restored, 0);
  assert.equal(digest(await readFile(failure.receiptFile)), failure.receiptDigest, 'A later success preserves the failed receipt');
  const override = run(['scripts/check.mjs'], 1, process.execPath, { ...process.env, EMMY_TLC_JAR: join(root, '.local/missing-override.jar') });
  assert.equal(override.status, 'refused');
  const jar = join(root, '.local/tools', coverage.tool.filename); const originalJar = await readFile(jar);
  await rm(jar); await writeFile(jar, 'corrupt existing jar');
  const corrupt = await check('pass', 1); assert.match(corrupt.reason, /differs from pinned/);
  await rm(jar); await writeFile(join(root, '.local/original-tool.jar'), originalJar);
  const preload = join(root, '.local/fetch-tools.mjs');
  await writeFile(preload, `import { readFileSync, writeFileSync } from 'node:fs';\nglobalThis.fetch=async url=>{if(url!==${JSON.stringify(coverage.tool.url)})throw new Error('Unexpected network request');writeFileSync('.local/tools-fetch.json',JSON.stringify({url,synthetic:true}));return new Response(readFileSync('.local/original-tool.jar'));};\n`);
  const coldEnv = { ...process.env, NODE_OPTIONS: `${process.env.NODE_OPTIONS ?? ''} --import ${pathToFileURL(preload).href}` };
  delete coldEnv.EMMY_TLC_JAR;
  const cold = run(['scripts/check.mjs', '--base', 'acceptance-base'], 0, process.execPath, coldEnv);
  assert.equal(cold.status, 'passed-local'); await assess(cold, 0, coldEnv);
  assert.equal(digest(await readFile(jar)), coverage.tool.sha256);
  assert.equal(JSON.parse(await readFile(join(root, '.local/tools-fetch.json'))).url, coverage.tool.url);
  const toolsOnly = run(['scripts/verify-publication.mjs', '--prepare-tools'], 0, process.execPath, coldEnv);
  assert.equal(toolsOnly.status, 'tools-ready'); assert.equal(toolsOnly.sourceReviewGate, false); assert.equal(toolsOnly.baseline, undefined);
  const report = { status: 'passed', syntheticFixedPlan: true, syntheticToolAcquisition: true, fixtureRoot: root, cases: ['npm-ingress', 'fresh-cli', 'source-drift', 'installed-dependency-drift', 'head-drift', 'exit-failure', 'signal', 'mid-run-source', 'mid-run-base', 'missing-suite', 'reordered-suite', 'failed-result', 'different-host', 'different-node', 'corrupt-output', 'wrong-receipt-hash', 'restored-original', 'failure-preserved', 'uploaded-failure-output', 'missing-tool-override', 'corrupt-existing-tool', 'cold-tool-cache', 'tools-ready-is-not-model-pass'], commands, receipts: { green, failure, signalled, drift, moved, restored, cold } };
  await writeFile(join(directory, 'report.json'), `${JSON.stringify(report, null, 2)}\n`);
  return report;
}
